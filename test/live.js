// 배포된 서버에서 한 판 빠르게 돌려 보기: URL=https://... PIN=1234 node test/live.js
'use strict';
const { io } = require('socket.io-client');
const URL = process.env.URL, PIN = process.env.PIN || '1234';
const conn = () => new Promise((res, rej) => { const s = io(URL, { transports: ['websocket'], forceNew: true }); s.on('connect', () => res(s)); s.on('connect_error', rej); });
const emit = (s, e, d) => new Promise((r) => s.emit(e, d, r));
const next = (s, e, f) => new Promise((res, rej) => { const t = setTimeout(() => rej(new Error('timeout ' + e)), 8000); const h = (d) => { if (!f || f(d)) { clearTimeout(t); s.off(e, h); res(d); } }; s.on(e, h); });
let fails = 0; const check = (c, m) => { console.log((c ? '  ✔ ' : '  ✘ ') + m); if (!c) fails++; };
(async () => {
  const op = await conn();
  let list = null; op.on('ops:list', (d) => (list = d));
  check((await emit(op, 'op:auth', { pin: PIN })).ok, 'PIN 로그인');
  const reg = await emit(op, 'op', { action: 'register', teamName: 'LIVE-TEST', members: ['테스트A', '테스트B'] });
  check(reg.ok, '팀 등록');
  check((await emit(op, 'op', { action: 'start', id: reg.id })).ok, '시작 → 방탈출');
  await new Promise((r) => setTimeout(r, 500));
  const s = list.sessions.find((x) => x.id === reg.id);
  const A = await conn(), B = await conn();
  const ja = await emit(A, 'sus:join', { code: s.suspects[0].code });
  const jb = await emit(B, 'sus:join', { code: s.suspects[1].code });
  check(ja.ok && jb.ok, '용의자 A, B 코드로 접속');
  const intoA = next(A, 'sus:state', (v) => v.phase === 'interrogation');
  check((await emit(op, 'op', { action: 'arrest', id: reg.id })).ok, '체포');
  const va = await intoA;
  check(va.rules && va.rules.CC === 3, '심문 시작 (보상표 3/0/5/1)');
  const gotA = next(A, 'sus:state', (v) => v.chat.some((m) => m.text === 'LIVE 압박'));
  await emit(op, 'op', { action: 'send', id: reg.id, seat: 0, text: 'LIVE 압박' });
  await gotA;
  const bLog = []; A.onAny((e, d) => bLog.push(JSON.stringify(d)));
  await emit(B, 'sus:send', { text: 'LIVE 답장 B' });
  await new Promise((r) => setTimeout(r, 500));
  check(!bLog.join('').includes('LIVE 답장 B'), 'A는 B의 채팅을 받지 않음');
  const waitA = next(A, 'sus:state', (v) => v.awaitingReveal);
  await emit(A, 'sus:choose', { choice: 'C' });
  await emit(B, 'sus:choose', { choice: 'D' });
  const wa = await waitA;
  check(wa.awaitingReveal && !wa.verdict, '둘 다 골라도 공개 전에는 결과가 안 나옴');
  const vA = next(A, 'sus:state', (v) => v.phase === 'verdict');
  const vB = next(B, 'sus:state', (v) => v.phase === 'verdict');
  check((await emit(op, 'op', { action: 'reveal', id: reg.id })).ok, '결과 공개');
  const [ra, rb] = await Promise.all([vA, vB]);
  check(ra.verdict.myPayout === 0 && rb.verdict.myPayout === 5, '판결: A 협력 캔디 0 / B 배반 캔디 5');
  check((await emit(op, 'op', { action: 'remove', id: reg.id })).ok, '테스트 세션 삭제');
  check((await emit(op, 'op:resetStats', {})).ok, '누적 통계 초기화');
  [op, A, B].forEach((x) => x.close());
  console.log(fails ? '실패 ' + fails : '라이브 확인 통과');
  process.exit(fails ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
